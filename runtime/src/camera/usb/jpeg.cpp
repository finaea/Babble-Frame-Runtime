bool decode_gray(const uint8_t *data, size_t size, uint8_t *out, size_t capacity, int *width, int *height) {
    // Many webcams leave the Huffman tables out of MJPEG frames, and stb_image would decode those to stripes.
    std::vector<uint8_t> fixed;
    if (const size_t sos = sos_without_dht(data, size)) {
        fixed.reserve(size + sizeof(kStandardDht));
        fixed.insert(fixed.end(), data, data + sos);
        fixed.insert(fixed.end(), kStandardDht, kStandardDht + sizeof(kStandardDht));
        fixed.insert(fixed.end(), data + sos, data + size);
        data = fixed.data();
        size = fixed.size();
    }
    int w = 0, h = 0, channels = 0;
    stbi_uc *px = stbi_load_from_memory(data, int(size), &w, &h, &channels, 1);
    if (!px)
        return false;
    const bool fits = size_t(w) * size_t(h) <= capacity;
    if (fits)
        memcpy(out, px, size_t(w) * size_t(h));
    stbi_image_free(px);
    *width = w;
    *height = h;
    return fits;
}

