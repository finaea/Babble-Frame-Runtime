// Walks the marker segments up to SOS, and returns its offset if no DHT came before it (0 otherwise).
size_t sos_without_dht(const uint8_t *data, size_t size) {
    if (size < 4 || data[0] != 0xff || data[1] != 0xd8)
        return 0;
    size_t i = 2;
    while (i + 1 < size) {
        if (data[i] != 0xff)
            return 0;
        while (i + 1 < size && data[i + 1] == 0xff)
            i++;
        if (i + 1 >= size)
            return 0;
        const uint8_t marker = data[i + 1];
        if (marker == 0xda)
            return i;
        if (marker == 0xc4 || i + 3 >= size)
            return 0;
        if (marker == 0x01 || (marker >= 0xd0 && marker <= 0xd7)) {
            i += 2;
            continue;
        }
        i += 2 + ((size_t(data[i + 2]) << 8) | data[i + 3]);
    }
    return 0;
}

